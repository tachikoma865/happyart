def main():
    force = "--force" in sys.argv
    only = [a for a in sys.argv[1:] if not a.startswith("--")]
    os.makedirs(OUT_DIR, exist_ok=True)

    items = [(k, "choice", v) for k, v in REEL_TEXTS.items()]
    items += [(k, "info", v) for k, v in INFO_SCRIPTS.items()]
    items.sort(key=lambda x: x[0])
    print(f"リールを作ります（選択占い{len(REEL_TEXTS)}本 / 情報系{len(INFO_SCRIPTS)}本）")
    print()

    made = 0
    for i, (name, kind, data) in enumerate(items):
        if only and name not in only:
            continue
        out = f"{OUT_DIR}/{name}.mp4"
        if is_valid(out) and not (force or only):
            print(f"  [skip] {name}.mp4（作成済み・検証OK）")
            continue

        t0 = time.time()
        print(f"  [{i + 1}/{len(items)}] {name}.mp4 を作成中...", flush=True)
        try:
            # seed と BGM を1本ずつずらす。8月と被らないよう起点もずらす
            if kind == "choice":
                hook, results, trio = data
                _, bgm, sec = make_reel(out, hook=hook, results=results,
                                        seed=911 + i * 23, bgm_index=i + 3, trio=trio)
            else:
                title, points, color, cta = data
                _, bgm, sec = make_info_reel(out, title, points, color=color,
                                             cta=cta, seed=911 + i * 23, bgm_index=i + 3)
        except RuntimeError as e:
            print(f"        [ERROR] {e}")
            sys.exit(1)
        mb = os.path.getsize(out) / 1024 / 1024
        print(f"        完了 {sec:.0f}秒 / {mb:.1f}MB / BGM {os.path.basename(bgm)}"
              f" （{time.time() - t0:.0f}秒かかりました）")
        made += 1

    print()
    print(f"作成: {made}本 / 合計 {len(items)}本")
    print(f"出力先: {OUT_DIR}/")
    print()
    print("次は build_september.py を実行して、CSVの media_type を REELS に切り替えてください。")


if __name__ == "__main__":
    main()
