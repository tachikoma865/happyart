def is_valid(path, tolerance=None):
    """
    出来上がった動画がちゃんと再生できる長さになっているか確認する。

    生成が途中で止まると、再生できない壊れたファイルが残る。
    「ファイルが存在する＝完成」で判定すると、それを完成扱いして素通りし、
    壊れた動画がそのまま投稿されてしまう。長さまで見て判定する。
    """
    if not os.path.exists(path) or os.path.getsize(path) < 80_000:
        return False
    try:
        r = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration",
             "-of", "csv=p=0", path],
            capture_output=True, text=True, timeout=30)
        if r.returncode != 0 or not r.stdout.strip():
            return False
        return float(r.stdout.strip()) >= MIN_SEC
    except Exception:
        return False

