def build_csv():
    """
    既存CSVに9月分を追記する。

    ★8月分の行（posted / pending / cancelled と threads_* の状態）には
      一切触れない。9月分の行だけを入れ替える（再実行しても安全）。
    """
    print("[2/3] posts_schedule.csv に9月分を追記中...")
    with open(CSV_FILE, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        headers = list(reader.fieldnames)
        rows = list(reader)

    extra_cols = [c for c in headers
                  if c not in ("id", "post_time", "media_url", "media_type",
                               "caption", "status", "posted_at", "instagram_post_id")]

    others, prev_sept = [], {}
    for r in rows:
        fname = r["media_url"].rsplit("/", 1)[-1]
        stem = fname.rsplit(".", 1)[0]
        # 9月分かどうかはURLのディレクトリでも判定する（8月にも 01_choice 等があるため）
        if stem in SEPT_STEMS and ("/sep/" in r["media_url"]):
            prev_sept[stem] = r
        else:
            others.append(r)

    start_id = max(int(r["id"]) for r in others) + 1 if others else 1
    kept = 0
    new_rows = []
    for i, p in enumerate(ALL_POSTS):
        url, mtype = media_for(p)
        row = {
            "id": start_id + i,
            "post_time": f"{p['date']} 21:00:00",
            "media_url": url,
            "media_type": mtype,
            "caption": full_caption(p),
            "status": "draft", "posted_at": "", "instagram_post_id": "",
        }
        for c in extra_cols:
            row[c] = ""
        prev = prev_sept.get(p["file"])
        if prev is not None:
            kept += 1
            row["status"] = prev.get("status", "draft")
            row["posted_at"] = prev.get("posted_at", "")
            row["instagram_post_id"] = prev.get("instagram_post_id", "")
            for c in extra_cols:
                row[c] = prev.get(c, "")
        new_rows.append(row)

    with open(CSV_FILE, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=headers)
        w.writeheader()
        w.writerows(others)
        w.writerows(new_rows)
    print(f"      → 8月分など既存 {len(others)}行は無変更 / "
          f"9月分 {len(new_rows)}行を追記（状態維持 {kept}件・新規 draft {len(new_rows) - kept}件）")


